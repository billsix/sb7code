"""Named colors from ``sb7color.h`` ported to numpy.

Mechanical translation of ``include/sb7color.h`` plus the
hex values from ``src/sb7/sb7color.cpp``. Each color is a
``numpy.float32`` ``vec4`` (RGB normalized to [0, 1], alpha = 1.0).

Usage mirrors the C++ side::

    color = colors.Color.CornflowerBlue
    GL.glClearBufferfv(GL.GL_COLOR, 0, color)

Read C++ ``sb7::color::Foo``, write Python ``colors.Color.Foo``.
"""

from __future__ import annotations

import numpy as np


def _hex(rgb: int) -> np.ndarray:
    return np.array(
        [
            ((rgb >> 16) & 0xFF) / 255.0,
            ((rgb >> 8) & 0xFF) / 255.0,
            (rgb & 0xFF) / 255.0,
            1.0,
        ],
        dtype=np.float32,
    )


